#!/usr/bin/env python3
"""Regenerate ffxi-event/src/opcode_table.rs from the parity ledger.

The ledger (.agents/skills/retail-observe/references/data/opcode-parity-ledger.md) already holds a
row per dispatch slot of FFXiMain's interpreter jump table; this mirrors it into Rust source so
the kuluu tree carries the 1:1 opcode reference next to the VM that answers it. Re-run after every
`scripts/opcode-parity-ledger.py` regeneration.

Usage: python scripts/opcode-table-embed.py [--check]
"""
import argparse
import pathlib
import re

LEDGER = ".agents/skills/retail-observe/references/data/opcode-parity-ledger.md"
OUT = "ffxi-event/src/opcode_table.rs"
VERDICTS = {
    "MATCH": "Match",
    "MATCH-ADVANCE": "MatchAdvance",
    "NO-ARM": "NoArm",
    "UNAUDITED": "Unaudited",
    "WIDTH-ONLY": "WidthOnly",
}
ROW_RE = re.compile(
    r"\| ([0-9A-F]{2}) \| (f_[0-9a-f]{6,}) \| (.*) \| (\S+) / (\S+) \| (\d) / \d \| (\d) / \d"
    r" \| (\S+) \| (\S+)(?: \|.*)?\s*$"
)


def parse(ledger_path):
    rows = []
    for line in pathlib.Path(ledger_path).read_text(encoding="utf-8").splitlines():
        m = ROW_RE.match(line)
        if not m:
            continue
        def num(s):
            return None if s == "-" else int(s)

        rows.append({
            "op": int(m.group(1), 16),
            "handler": m.group(2),
            "form": re.sub(r"\s*\[audit.*$", "", m.group(3)).strip(),
            "dll_width": num(m.group(4)),
            "kuluu_width": num(m.group(5)),
            "jumps_dll": m.group(6) == "1",
            "yields_dll": m.group(7) == "1",
            "kuluu": None if m.group(8) == "-" else m.group(8),
            "verdict": VERDICTS[m.group(9)],
        })
    return rows


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def opt(v):
    return "None" if v is None else f"Some({v})"


def opt_quoted(v):
    return "None" if v is None else f"Some({rust_str(v)})"


def emit(rows):
    counts = {}
    for r in rows:
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    census = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
    lines = [
        "//! One-for-one mirror of the event interpreter's own opcode dispatch table.",
        "//!",
        "//! FFXiMain.dll declares its event opcodes as a jump table of slots 0x00..=0xDA (the build,",
        "//! handler symbols and step amounts recorded by `scripts/opcode-parity-ledger.py`); there is",
        "//! no other instruction table - see the record",
        "//! `.agents/skills/retail-observe/references/2026-10-28-event-opcode-no-skip-pass.md`,",
        '//! section "Where FFXiMain gets its opcode table". This array is that table in Rust: one row',
        "//! per slot, naming the retail handler, what it does to exec and the yield byte, the kuluu",
        "//! constant answering it (when one exists), and the parity verdict of the last audit.",
        "//!",
        "//! Generated by `scripts/opcode-table-embed.py` from the generated ledger; do not hand-edit.",
        f"//! Census at generation: {census}.",
        "",
        "/// Parity status of a slot per the opcode-parity ledger audit trail.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum Verdict {",
        "    /// Handler read to the last instruction; kuluu answers it rule-for-rule (arm or width).",
        "    Match,",
        "    /// Width matches and the handler demonstrably does nothing more beyond advancing.",
        "    MatchAdvance,",
        '    /// Read; deliberately left a width-only skip (the ledger row carries the audit reason).',
        "    NoArm,",
        "    /// Not yet read to the last instruction - this is the open work queue.",
        "    Unaudited,",
        "    /// Width table only so far; handler not compared path-by-path.",
        "    WidthOnly,",
        "}",
        "",
        "/// One dispatch slot of retail's event opcode jump table (0x00..=0xDA).",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Slot {",
        "    /// The opcode byte itself.",
        "    pub op: u8,",
        "    /// Retail's handler function symbol in the recorded client build.",
        "    pub handler: &'static str,",
        "    /// What the handler does to exec and the yield byte, extracted from its instruction",
        '    /// stream (e.g. `add 5`, `jump-set x1`, `COND-add(None)+computed`).',
        "    pub exec_form: &'static str,",
        "    /// The handler's fixed step-past width; None when computed/conditional or jumping.",
        "    pub dll_width: Option<u8>,",
        "    /// `opcode_meta`'s declared width (its widest-case row for sub-dispatched families).",
        "    pub kuluu_width: Option<u8>,",
        "    /// Some path sets exec non-linearly.",
        "    pub jumps_dll: bool,",
        "    /// Some path writes the scheduler yield byte.",
        "    pub yields_dll: bool,",
        "    /// The kuluu `OP_*` constant this slot answers through, when one exists.",
        "    pub kuluu: Option<&'static str>,",
        "    pub verdict: Verdict,",
        "}",
        "",
        f"/// All {len(rows)} dispatch slots, in opcode order.",
        # One row per slot on one line each is the point of the table - rustfmt would wrap every
        # row into eight lines and make the drift this file exists to show unreadable.
        "#[rustfmt::skip]",
        "pub const SLOTS: &[Slot] = &[",
    ]
    for r in rows:
        lines.append(
            f"    Slot {{ op: 0x{r['op']:02X}, handler: {rust_str(r['handler'])},"
            f" exec_form: {rust_str(r['form'])}, dll_width: {opt(r['dll_width'])},"
            f" kuluu_width: {opt(r['kuluu_width'])}, jumps_dll: {str(r['jumps_dll']).lower()},"
            f" yields_dll: {str(r['yields_dll']).lower()}, kuluu:"
            f" {opt_quoted(r['kuluu'])}, verdict: Verdict::{r['verdict']} }},"
        )
    lines += [
        "];",
        "",
        "/// The slot record for an opcode byte, when the dispatch declares it.",
        "pub fn lookup(op: u8) -> Option<&'static Slot> {",
        "    SLOTS.iter().find(|s| s.op == op)",
        "}",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    /// The table is the dispatch: slots 0x00..=0xDA, contiguous and in order.",
        "    #[test]",
        "    fn covers_the_dispatch_contiguously() {",
        f"        assert_eq!(SLOTS.len(), {len(rows)});",
        "        for (i, slot) in SLOTS.iter().enumerate() {",
        "            assert_eq!(slot.op, i as u8, \"slot order at row {i}\");",
        "        }",
        "    }",
        "",
        "    #[test]",
        "    fn every_slot_names_a_handler_and_an_exec_form() {",
        "        for slot in SLOTS {",
        "            assert!(slot.handler.starts_with(\"f_\"), \"handler at {:02X}\", slot.op);",
        "            assert!(!slot.exec_form.is_empty(), \"exec form at {:02X}\", slot.op);",
        "        }",
        "    }",
        "",
        "    /// Spot-checks against the crate's own constants: a renamed or renumbered opcode trips.",
        "    #[test]",
        "    fn named_arrows_match_the_dispatch_slots() {",
        "        use crate::opcode_meta::*;",
        "        for (op, name) in [",
        "            (OP_WINDOW, \"OP_WINDOW\"),",
        "            (OP_MENU, \"OP_MENU\"),",
        "            (OP_RENDERFLAG, \"OP_RENDERFLAG\"),",
        "            (OP_SUBSCHED, \"OP_SUBSCHED\"),",
        "            (OP_FLAGWORD_SELECTOR, \"OP_FLAGWORD_SELECTOR\"),",
        "        ] {",
        "            let slot = lookup(op).unwrap_or_else(|| panic!(\"{name} absent from table\"));",
        "            assert_eq!(slot.kuluu, Some(name), \"{name} row drifted\");",
        "        }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the Rust table is stale")
    a = ap.parse_args()
    rows = parse(LEDGER)
    assert len(rows) == 0xDB, f"expected {0xDB} slots, parsed {len(rows)} - ledger format drift?"
    text = emit(rows)
    path = pathlib.Path(OUT)
    if a.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        return 0 if current == text else 1
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(rows)} slots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
